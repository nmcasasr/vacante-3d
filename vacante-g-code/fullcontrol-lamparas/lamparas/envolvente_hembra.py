def envolvente(d):
    """Radio máximo admisible a la fase de hélice d (mm), interpolado."""
    x = (d % PASO) / PASO * N
    i = int(x) % N
    f = x - int(x)
    return ENVOLVENTE[i] * (1 - f) + ENVOLVENTE[(i + 1) % N] * f
